package ide

// This source-only shim uses the installed xcross router for marked and stock
// launches. Framing is byte-based: DAP Content-Length counts UTF-8 bytes.
const shim = `// GENERATED by Blackburn. Re-run blackburn ide config to update.
import 'dart:async';
import 'dart:convert';
import 'dart:io';

Future<void> main(List<String> args) async {
  Process? dap;
  IOSink? log;
  try {
    dap = await Process.start('xcross', [
      'flutter', 'dap',
      if (args.contains('--test')) '--test',
      if (args.contains('--test')) '--',
      if (args.contains('--test')) ...args.where((a) => a != 'debug_adapter' && a != '--test'),
    ]);
    final child = dap;
    final project = File.fromUri(Platform.script).parent.parent;
    final runtime = Directory('${project.path}/.dart_tool/blackburn');
    await runtime.create(recursive: true);
    log = File('${runtime.path}/xcross.log').openWrite();
    final sink = log;
    final signals = <StreamSubscription<ProcessSignal>>[
      ProcessSignal.sigterm.watch().listen((_) => child.kill()),
      ProcessSignal.sigint.watch().listen((_) => child.kill(ProcessSignal.sigint)),
    ];
    final output = child.stdout.forEach((data) {
      stdout.add(data);
      // Retain DAP output event text, never raw DAP frames or source variables.
      outputBytes.addAll(data);
      drain(outputBytes, (message) {
        if (message['event'] == 'output') {
          final body = message['body'];
          if (body is Map && body['output'] is String) sink.write(body['output']);
        }
      });
    });
    final errors = stderr.addStream(child.stderr);
    final input = stdin.listen((data) {
      try {
        inputBytes.addAll(data);
        drain(inputBytes, (message) {
          if (message['command'] == 'launch') {
            final launch = message['arguments'] as Map<String, dynamic>;
            final env = launch['env'];
            if (env is Map && env['XCROSS'] == 'true' &&
                launch['args'] is List &&
                (launch['args'] as List).contains('__BLACKBURN_LEASED_UDID__')) {
              final ready = jsonDecode(File('${runtime.path}/launch.json').readAsStringSync()) as Map;
              final argv = launch['args'] as List;
              if (ready['device'] is! String || (ready['device'] as String).isEmpty) throw StateError('No leased simulator');
              launch['args'] = argv.map((v) => v == '__BLACKBURN_LEASED_UDID__' ? ready['device'] : v).toList();
              launch['env'] = {...env, ...ready['environment'] as Map};
            }
          }
          final body = utf8.encode(jsonEncode(message));
          child.stdin.add(ascii.encode('Content-Length: ${body.length}\r\n\r\n'));
          child.stdin.add(body);
        });
      } catch (e) {
        stderr.writeln('blackburn DAP: $e; run blackburn ide f5 first');
        child.kill();
      }
    }, onDone: () { child.stdin.close(); child.kill(); });
    final code = await child.exitCode;
    await input.cancel();
    await output;
    await errors;
    for (final signal in signals) { await signal.cancel(); }
    await sink.flush();
    await sink.close();
    exit(code);
  } catch (e) {
    stderr.writeln('blackburn DAP: $e');
    dap?.kill();
    await log?.close();
    exit(2);
  }
}
final inputBytes = <int>[];
final outputBytes = <int>[];
void drain(List<int> buffer, void Function(Map<String, dynamic>) consume) {
  while (true) {
    var end = -1;
    for (var i = 0; i + 3 < buffer.length; i++) {
      if (buffer[i] == 13 && buffer[i+1] == 10 && buffer[i+2] == 13 && buffer[i+3] == 10) { end = i; break; }
    }
    if (end < 0) { if (buffer.length > 8192) throw FormatException('DAP header too large'); return; }
    final header = ascii.decode(buffer.sublist(0, end));
    final match = RegExp(r'Content-Length: (\d+)', caseSensitive: false).firstMatch(header);
    if (match == null) throw FormatException('Missing Content-Length');
    final length = int.parse(match.group(1)!);
    if (length > 16 * 1024 * 1024) throw FormatException('DAP frame too large');
    if (buffer.length < end + 4 + length) return;
    final message = jsonDecode(utf8.decode(buffer.sublist(end + 4, end + 4 + length))) as Map<String, dynamic>;
    buffer.removeRange(0, end + 4 + length);
    consume(message);
  }
}
`
