// Package appliance implements a versioned sparse, checksummed VM interchange format.
// It never starts a VM or executes commands from an imported configuration.
package appliance

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/klauspost/compress/zstd"
	"github.com/pelletier/go-toml/v2"
)

const magic = "BLACKBURN-SPARSE-1\n"
const block = 1024 * 1024
const maxSize = int64(16 * 1024 * 1024 * 1024 * 1024)

type File struct {
	Name   string `json:"name"`
	Size   int64  `json:"size"`
	SHA256 string `json:"sha256"`
}
type Manifest struct {
	Version      int    `json:"version"`
	Architecture string `json:"architecture"`
	Files        []File `json:"files"`
}

func safe(s string) bool {
	return s != "" && s != "." && s != ".." && filepath.Base(s) == s && !strings.ContainsAny(s, "/\\\x00")
}
func (m Manifest) Validate() error {
	if m.Version != 1 || m.Architecture != "x86_64" || len(m.Files) < 2 || len(m.Files) > 64 {
		return fmt.Errorf("unsupported appliance manifest")
	}
	seen := map[string]bool{}
	total := int64(0)
	for _, f := range m.Files {
		h, e := hex.DecodeString(f.SHA256)
		if !safe(f.Name) || seen[f.Name] || f.Size < 0 || f.Size > maxSize || e != nil || len(h) != 32 {
			return fmt.Errorf("invalid manifest file %q", f.Name)
		}
		if (f.Name == "vm.toml" || f.Name == "blackburn.toml") && f.Size > 1024*1024 {
			return fmt.Errorf("configuration file too large: %s", f.Name)
		}
		seen[f.Name] = true
		total += f.Size
		if total > maxSize {
			return fmt.Errorf("appliance exceeds 16 TiB logical limit")
		}
	}
	if !seen["vm.toml"] || !seen["blackburn.toml"] {
		return fmt.Errorf("configuration files missing")
	}
	return nil
}

// References restricts provider disk/firmware paths to self-contained regular files.
// Host-specific environment values are replaced by the importer/next profile launch.
func References(data []byte) ([]string, error) {
	var v map[string]any
	if e := toml.Unmarshal(data, &v); e != nil {
		return nil, e
	}
	names := []string{"vm.toml"}
	disk, ok := v["disk"].(string)
	if !ok || !safe(disk) {
		return nil, fmt.Errorf("VM needs a relative, self-contained disk")
	}
	names = append(names, disk)
	q, _ := v["q35"].(map[string]any)
	for _, k := range []string{"opencore", "firmware_code", "firmware_vars"} {
		s, _ := q[k].(string)
		if !safe(s) {
			return nil, fmt.Errorf("q35.%s must be a relative filename", k)
		}
		names = append(names, s)
	}
	// Arbitrary extra QEMU arguments may reference host files or devices. Only the
	// network and disk tuning flags generated by Blackburn are portable.
	if args, ok := v["extra_args"].([]any); ok {
		for i := 0; i < len(args); i += 2 {
			if i+1 >= len(args) {
				return nil, fmt.Errorf("unpaired extra_args")
			}
			key, _ := args[i].(string)
			value, _ := args[i+1].(string)
			switch key {
			case "-netdev":
				if !strings.HasPrefix(value, `{"type":"passt"`) {
					return nil, fmt.Errorf("nonportable netdev")
				}
			case "-device":
				if !strings.HasPrefix(value, "virtio-net-pci,") {
					return nil, fmt.Errorf("nonportable device")
				}
			case "-set":
				if !strings.HasPrefix(value, "drive.disk.cache=") && value != "drive.disk.discard=unmap" {
					return nil, fmt.Errorf("nonportable drive tuning")
				}
			case "-display":
				if value != "none" {
					return nil, fmt.Errorf("nonportable display")
				}
			default:
				return nil, fmt.Errorf("nonportable QEMU argument %q", key)
			}
		}
	}
	sort.Strings(names)
	seen := map[string]bool{}
	for _, s := range names {
		if seen[s] || s == "blackburn.toml" {
			return nil, fmt.Errorf("duplicate VM reference")
		}
		seen[s] = true
	}
	return names, nil
}
func fileHash(path string) (File, error) {
	s, e := os.Lstat(path)
	if e != nil {
		return File{}, e
	}
	if !s.Mode().IsRegular() {
		return File{}, fmt.Errorf("not a regular file: %s", path)
	}
	f, e := os.Open(path)
	if e != nil {
		return File{}, e
	}
	defer f.Close()
	if e = standalone(f, path); e != nil {
		return File{}, e
	}
	if _, e = f.Seek(0, io.SeekStart); e != nil {
		return File{}, e
	}
	h := sha256.New()
	n64, e := io.Copy(h, f)
	if e != nil {
		return File{}, e
	}
	if n64 != s.Size() {
		return File{}, fmt.Errorf("file changed during export")
	}
	return File{filepath.Base(path), n64, hex.EncodeToString(h.Sum(nil))}, nil
}

// Export uses two bounded-memory passes. Zero blocks are omitted even without
// compression. Output publication is atomic and never overwrites an existing file.
func Export(dir, configPath, output, compression string) error {
	if compression != "none" && compression != "zstd" {
		return fmt.Errorf("compression must be zstd or none")
	}
	data, e := os.ReadFile(filepath.Join(dir, "vm.toml"))
	if e != nil {
		return e
	}
	names, e := References(data)
	if e != nil {
		return e
	}
	paths := map[string]string{"blackburn.toml": configPath}
	for _, s := range names {
		paths[s] = filepath.Join(dir, s)
	}
	names = append(names, "blackburn.toml")
	sort.Strings(names)
	m := Manifest{Version: 1, Architecture: "x86_64"}
	for _, s := range names {
		f, e := fileHash(paths[s])
		if e != nil {
			return e
		}
		f.Name = s
		m.Files = append(m.Files, f)
	}
	if e = m.Validate(); e != nil {
		return e
	}
	f, e := os.CreateTemp(filepath.Dir(output), ".appliance-*")
	if e != nil {
		return e
	}
	defer os.Remove(f.Name())
	defer f.Close()
	var w io.Writer = f
	var z *zstd.Encoder
	if compression == "zstd" {
		z, e = zstd.NewWriter(f, zstd.WithEncoderConcurrency(1))
		if e != nil {
			return e
		}
		defer z.Close()
		w = z
	}
	b, _ := json.Marshal(m)
	if _, e = io.WriteString(w, magic); e != nil {
		return e
	}
	if e = binary.Write(w, binary.LittleEndian, uint32(len(b))); e != nil {
		return e
	}
	if _, e = w.Write(b); e != nil {
		return e
	}
	buf := make([]byte, block)
	zero := make([]byte, block)
	for _, entry := range m.Files {
		src, e := os.Open(paths[entry.Name])
		if e != nil {
			return e
		}
		h := sha256.New()
		offset := int64(0)
		for offset < entry.Size {
			n := int(min(int64(block), entry.Size-offset))
			_, e = io.ReadFull(src, buf[:n])
			if e != nil {
				src.Close()
				return e
			}
			h.Write(buf[:n])
			if !bytes.Equal(buf[:n], zero[:n]) {
				if e = record(w, offset, uint32(n)); e == nil {
					_, e = w.Write(buf[:n])
				}
				if e != nil {
					src.Close()
					return e
				}
			}
			offset += int64(n)
		}
		var extra [1]byte
		n, readErr := src.Read(extra[:])
		src.Close()
		if n != 0 || readErr != io.EOF || hex.EncodeToString(h.Sum(nil)) != entry.SHA256 {
			return fmt.Errorf("source changed: %s", entry.Name)
		}
		if e = record(w, entry.Size, 0); e != nil {
			return e
		}
	}
	if z != nil {
		if e = z.Close(); e != nil {
			return e
		}
	}
	if e = f.Sync(); e != nil {
		return e
	}
	if e = f.Close(); e != nil {
		return e
	}
	return os.Link(f.Name(), output)
}
func record(w io.Writer, offset int64, n uint32) error {
	if e := binary.Write(w, binary.LittleEndian, uint64(offset)); e != nil {
		return e
	}
	return binary.Write(w, binary.LittleEndian, n)
}

// Extract writes only into a new staging directory owned by the caller. It
// validates all sparse extents, logical hashes, references and the stream footer.
func Extract(input, dir string) (Manifest, error) {
	var m Manifest
	f, e := os.Open(input)
	if e != nil {
		return m, e
	}
	defer f.Close()
	br := bufio.NewReader(f)
	var r io.Reader = br
	prefix, e := br.Peek(4)
	if e != nil {
		return m, e
	}
	if bytes.Equal(prefix, []byte{0x28, 0xb5, 0x2f, 0xfd}) {
		z, e := zstd.NewReader(br, zstd.WithDecoderConcurrency(1), zstd.WithDecoderMaxMemory(256<<20))
		if e != nil {
			return m, e
		}
		defer z.Close()
		r = z
	}
	header := make([]byte, len(magic))
	if _, e = io.ReadFull(r, header); e != nil || string(header) != magic {
		return m, fmt.Errorf("invalid appliance header")
	}
	var size uint32
	if e = binary.Read(r, binary.LittleEndian, &size); e != nil {
		return m, e
	}
	if size > 1024*1024 {
		return m, fmt.Errorf("manifest too large")
	}
	b := make([]byte, size)
	if _, e = io.ReadFull(r, b); e != nil {
		return m, e
	}
	d := json.NewDecoder(bytes.NewReader(b))
	d.DisallowUnknownFields()
	if e = d.Decode(&m); e != nil {
		return m, e
	}
	if e = m.Validate(); e != nil {
		return m, e
	}
	buf := make([]byte, block)
	zero := make([]byte, block)
	for _, entry := range m.Files {
		dest, e := os.OpenFile(filepath.Join(dir, entry.Name), os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
		if e != nil {
			return m, e
		}
		e = func() error {
			defer dest.Close()
			h := sha256.New()
			pos := int64(0)
			for {
				var off uint64
				var n uint32
				if e := binary.Read(r, binary.LittleEndian, &off); e != nil {
					return e
				}
				if e := binary.Read(r, binary.LittleEndian, &n); e != nil {
					return e
				}
				if off > uint64(entry.Size) || off < uint64(pos) || n > block || int64(n) > entry.Size-int64(off) {
					return fmt.Errorf("invalid sparse extent")
				}
				if n == 0 && int64(off) != entry.Size {
					return fmt.Errorf("invalid sparse terminator")
				}
				for pos < int64(off) {
					k := min(int64(block), int64(off)-pos)
					h.Write(zero[:k])
					pos += k
				}
				if n == 0 {
					break
				}
				if _, e := io.ReadFull(r, buf[:n]); e != nil {
					return e
				}
				h.Write(buf[:n])
				if _, e := dest.WriteAt(buf[:n], int64(off)); e != nil {
					return e
				}
				pos += int64(n)
			}
			if hex.EncodeToString(h.Sum(nil)) != entry.SHA256 {
				return fmt.Errorf("checksum mismatch: %s", entry.Name)
			}
			if e := dest.Truncate(entry.Size); e != nil {
				return e
			}
			return dest.Sync()
		}()
		if e != nil {
			return m, e
		}
	}
	var tail [1]byte
	if n, e := r.Read(tail[:]); n != 0 || e != io.EOF {
		return m, fmt.Errorf("trailing or damaged appliance stream: %v", e)
	}
	data, e := os.ReadFile(filepath.Join(dir, "vm.toml"))
	if e != nil {
		return m, e
	}
	refs, e := References(data)
	if e != nil {
		return m, e
	}
	seen := map[string]bool{}
	for _, f := range m.Files {
		seen[f.Name] = true
	}
	if len(m.Files) != len(refs)+1 {
		return m, fmt.Errorf("unexpected files in appliance")
	}
	for _, s := range refs {
		if !seen[s] {
			return m, fmt.Errorf("missing VM file %s", s)
		}
	}
	// Check backing headers without another full logical-disk hashing pass.
	for _, s := range refs {
		path := filepath.Join(dir, s)
		f, e := os.Open(path)
		if e != nil {
			return m, e
		}
		e = standalone(f, path)
		f.Close()
		if e != nil {
			return m, e
		}
	}

	return m, nil
}

func standalone(f *os.File, path string) error {
	head := make([]byte, 20)
	n, e := f.Read(head)
	if e != nil && e != io.EOF {
		return e
	}
	if n == 20 && string(head[:4]) == "QFI\xfb" && binary.BigEndian.Uint32(head[16:20]) != 0 {
		return fmt.Errorf("flatten qcow2 backing chain before export: %s", path)
	}
	return nil
}
